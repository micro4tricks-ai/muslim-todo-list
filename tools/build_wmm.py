"""Build js/wmm-data.js: the World Magnetic Model coefficients, for the compass's declination.

The compass finds magnetic north; the qibla is measured from true (geographic) north. The
difference, the declination, comes from the World Magnetic Model of NOAA NCEI and the British
Geological Survey (public domain), read here from its official coefficient file, never typed.
The official test values are kept beside it (tools/wmm_testvalues.txt) for tools/test_compass.mjs.

Run:  python tools/build_wmm.py
"""
import io
import json
import os
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = 'https://www.ncei.noaa.gov/sites/default/files/2024-12/WMM2025COF.zip'


def main():
    req = urllib.request.Request(URL, headers={'User-Agent': 'muslim-todo-list-builder'})
    with urllib.request.urlopen(req, timeout=120) as r:
        z = zipfile.ZipFile(io.BytesIO(r.read()))
    cof = z.read('WMM2025COF/WMM.COF').decode('ascii').splitlines()
    tests = z.read('WMM2025COF/WMM2025_TestValues.txt').decode('ascii')
    epoch, model, date = cof[0].split()
    coef = []
    for line in cof[1:]:
        f = line.split()
        if not f or f[0].startswith('9999'):
            break
        n, m = int(f[0]), int(f[1])
        coef.append([n, m] + [float(x) for x in f[2:6]])
    assert len(coef) == 90 and coef[0][:2] == [1, 0] and coef[-1][:2] == [12, 12], len(coef)
    with open(os.path.join(ROOT, 'js', 'wmm-data.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/build_wmm.py from NOAA NCEI\'s %s coefficients (public domain). Do not edit by hand.\n' % model)
        f.write('// coef: [n, m, g, h, g per year, h per year] in nT, from the epoch.\n')
        f.write('(typeof window !== \'undefined\' ? window : globalThis).NOON_WMM = ')
        json.dump({'model': model, 'epoch': float(epoch), 'released': date, 'coef': coef}, f, separators=(',', ':'))
        f.write(';\n')
    with open(os.path.join(ROOT, 'tools', 'wmm_testvalues.txt'), 'w', encoding='ascii', newline='\n') as f:
        f.write(tests.replace('\r\n', '\n'))
    print(model, epoch, len(coef), 'coefficients')


if __name__ == '__main__':
    main()
