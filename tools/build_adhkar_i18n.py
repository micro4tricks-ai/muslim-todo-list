"""Build js/adhkar-i18n.js: the adhkar of js/adhkar-data.js in Urdu, Indonesian, Turkish and Spanish.

Two sources, nothing is written by hand or translated by a model:
  1. The Quran verses of the adhkar (those that are whole verses): the same translations the Quran
     reader opens on, from api.alquran.cloud (ur.jalandhry, id.indonesian, tr.diyanet, es.cortes).
  2. The duas of the Sunnah: the translation of the matching hadith in HadeethEnc (hadeethenc.com),
     a translated-hadith project supervised by a scholarly body. tools/adhkar_hadeeth_map.json says
     which HadeethEnc hadith holds each dua (found by comparing the Arabic, then checked by eye).
An item with no entry stays in English. Each entry carries its source for the page to show.

Run:  python tools/build_adhkar_i18n.py
"""
import json
import os
import re
import subprocess
import urllib.error
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'js', 'adhkar-i18n.js')
MAP = os.path.join(ROOT, 'tools', 'adhkar_hadeeth_map.json')
LANGS = ['ur', 'id', 'tr', 'es']
EDITION = {'ur': 'ur.jalandhry', 'id': 'id.indonesian', 'tr': 'tr.diyanet', 'es': 'es.cortes'}

# Items that are whole verses (a verse, a run of verses, or a basmala + a surah): item id -> [(surah, from, to)].
# A partial verse (a dua cut from the middle of one) is left in English: a translation of the whole verse
# would carry words the item does not.
VERSES = {
    'q1-1-7': [(1, 1, 7)],
    'q2-255': [(2, 255, 255)],
    'q2-285-286': [(2, 285, 286)],
    'q112-1-4': [(1, 1, 1), (112, 1, 4)],
    'q113-1-5': [(1, 1, 1), (113, 1, 5)],
    'q114-1-6': [(1, 1, 1), (114, 1, 6)],
    'h71': [(2, 255, 255)],
    'h100': [(2, 255, 255)],
    'h101': [(2, 285, 286)],
    'h4': [(3, 190, 200)],
    'h76': [(1, 1, 1), (112, 1, 4), (1, 1, 1), (113, 1, 5), (1, 1, 1), (114, 1, 6)],
    'h70': [(1, 1, 1), (112, 1, 4), (1, 1, 1), (113, 1, 5), (1, 1, 1), (114, 1, 6)],
}
SRC_QURAN = {'ur': 'قرآن — ترجمہ جالندھری', 'id': 'Al-Qur’an — terjemah Kemenag', 'tr': 'Kur’an — Diyanet meali', 'es': 'Corán — traducción de Cortés'}


def get(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'muslim-todo-list-builder'})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=40) as r:
                return json.loads(r.read().decode('utf-8'))
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return None  # no such page: HadeethEnc has no translation of this hadith in this language
            if attempt == 3:
                raise
        except OSError:
            if attempt == 3:
                raise
    raise RuntimeError(url)


def items():
    js = "global.window={};require(%s);console.log(JSON.stringify(window.NOON_ADHKAR.categories))" % json.dumps(ROOT.replace('\\', '/') + '/js/adhkar-data.js')
    cats = json.loads(subprocess.check_output(['node', '-e', js], text=True, encoding='utf-8'))
    return {it['id']: it for c in cats for it in c['items']}


def clean(s):
    return re.sub(r'\s+', ' ', s.replace('﻿', '')).strip()


def main():
    its = items()
    out = {l: {} for l in LANGS}

    # 1. the Quran
    surahs = {}
    for lang in LANGS:
        for sn in {s for refs in VERSES.values() for (s, _, _) in refs}:
            surahs[(lang, sn)] = [a['text'] for a in get(f'https://api.alquran.cloud/v1/surah/{sn}/{EDITION[lang]}')['data']['ayahs']]
    for iid, refs in VERSES.items():
        assert iid in its, iid
        for lang in LANGS:
            parts = []
            for sn, a, b in refs:
                v = surahs[(lang, sn)]
                parts.append(clean(' '.join(v[a - 1:b])))
            out[lang][iid] = {'t': ' '.join(parts), 's': SRC_QURAN[lang]}

    # 2. the duas of the Sunnah, from HadeethEnc
    if os.path.exists(MAP):
        m = json.load(open(MAP, encoding='utf-8'))
        for iid, hid in m.items():
            assert iid in its and iid not in VERSES, iid
            for lang in LANGS:
                d = get(f'https://hadeethenc.com/api/v1/hadeeths/one/?language={lang}&id={hid}')
                t = clean((d or {}).get('hadeeth') or '')
                if t:
                    out[lang][iid] = {'t': t, 's': f'HadeethEnc · {hid}'}
                else:
                    print('no', lang, 'translation of', iid, '(hadith', hid + ')')

    body = json.dumps(out, ensure_ascii=False, indent=0, separators=(',', ':'))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/build_adhkar_i18n.py (api.alquran.cloud, hadeethenc.com). Do not edit by hand.\n')
        f.write(f'window.NOON_ADHKAR_I18N = {body};\n')
    print(OUT, {l: len(v) for l, v in out.items()}, 'of', len(its))


if __name__ == '__main__':
    main()
