"""Build js/lang/surah-names.js: the 114 surah names in Urdu, Indonesian, Turkish and Spanish.

The names come from the MP3Quran.net API (https://mp3quran.net/api/v3/suwar?language=<code>), which
keeps them per language as the Complex's own translators wrote them. The app carries them so the
Quran, the hifz planner and the listening tab name a surah in the reader's language, offline.

Run:  python tools/build_surah_names.py
"""
import json
import re
import urllib.request

LANGS = ['ur', 'id', 'tr', 'es']
OUT = 'js/lang/surah-names.js'


def get(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'muslim-todo-list-builder'})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode('utf-8-sig'))


def clean(s):
    # The source leaves a BOM, line breaks and no-break spaces in some names.
    return re.sub(r'\s+', ' ', s.replace('﻿', '').replace('\xa0', ' ')).strip()


names = {}
for lang in LANGS:
    suwar = sorted(get(f'https://www.mp3quran.net/api/v3/suwar?language={lang}')['suwar'], key=lambda x: x['id'])
    assert [x['id'] for x in suwar] == list(range(1, 115)), lang
    names[lang] = [clean(x['name']) for x in suwar]
    assert all(names[lang]), lang

body = json.dumps(names, ensure_ascii=False, indent=1)
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/build_surah_names.py from the MP3Quran.net API. Do not edit by hand.\n')
    f.write(f'window.NOON_SURAH_NAMES = {body};\n')
print(OUT, {k: len(v) for k, v in names.items()})
